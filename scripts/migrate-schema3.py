def plan_text(path: Path, edits: list[tuple[str, str]]) -> tuple[str, bool]:
    """Apply every edit for one file to ONE string, in sequence. Never re-read.

    19g's defect exactly: every replacement computed from the ORIGINAL text and
    written one after another, so the second edit to a file discarded the first
    and the script said it had done both.
    """
    original = path.read_text(encoding="utf-8")
    text = original
    already = 0
    for anchor, replacement in edits:
        found = text.count(anchor)
        if found == 1:
            text = text.replace(anchor, replacement, 1)
            continue
        # Counted on the string as it stands, not on the original: an anchor
        # that a previous edit consumed is a defect in this script, and it must
        # not read as "already applied".
        if found == 0 and replacement in text:
            already += 1
            continue
        raise Refusal(
            f"{path.relative_to(ROOT)}: an anchor matched {found} times, expected exactly one.\n"
            f"    {anchor.strip().splitlines()[0][:100]}"
        )
    if already and already != len(edits):
        raise Refusal(
            f"{path.relative_to(ROOT)}: {already} of {len(edits)} edits are already applied. "
            f"That is a half-migrated file, which this script will not add to."
        )
    return text, already == len(edits)


def plan_json(path: Path, migrate) -> tuple[str, bool]:
    doc = json.loads(path.read_text(encoding="utf-8"))
    try:
        new = migrate(doc)
    except AlreadyApplied:
        return path.read_text(encoding="utf-8"), True
    return json.dumps(new, indent=2, ensure_ascii=False) + "\n", False


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true",
                        help="prove every anchor matches exactly once and write nothing")
    args = parser.parse_args(argv)

    planned: list[tuple[Path, str]] = []
    already: list[str] = []
    try:
        for name, edits in EDITS.items():
            path = ROOT / name
            if not path.is_file():
                raise Refusal(f"{name} does not exist")
            text, was_applied = plan_text(path, edits)
            (already.append(name) if was_applied else planned.append((path, text)))
        for name, migrate in JSON_MIGRATIONS.items():
            path = ROOT / name
            if not path.is_file():
                raise Refusal(f"{name} does not exist")
            text, was_applied = plan_json(path, migrate)
            (already.append(name) if was_applied else planned.append((path, text)))
    except Refusal as refusal:
        print(f"migrate-schema3: REFUSED\n{refusal}", file=sys.stderr)
        print("Nothing was written.", file=sys.stderr)
        return 2

    if already and planned:
        print(
            "migrate-schema3: REFUSED\n"
            f"already migrated: {', '.join(sorted(already))}\n"
            f"still to migrate: {', '.join(str(p.relative_to(ROOT)) for p, _ in planned)}\n"
            "A half-migrated tree is not a state this script will add to. Nothing was written.",
            file=sys.stderr,
        )
        return 2

    if already:
        print("migrate-schema3: already applied — every file is on schema 3, nothing to do.")
        print(f"  {len(already)} files: {', '.join(sorted(already))}")
        return 3

    if args.dry_run:
        print(f"migrate-schema3: {len(planned)} files would change; every anchor matched once.")
        for path, _ in planned:
            print(f"  {path.relative_to(ROOT)}")
        return 0

    # Every anchor in every file has matched by here, so this loop cannot stop
    # half way for a reason this script could have known about earlier.
    for path, text in planned:
        path.write_text(text, encoding="utf-8")
        print(f"  wrote {path.relative_to(ROOT)}")

    # NOT a string edit, on purpose: phases.json is generated, and a
    # hand-written copy of it beside its generator is a second definition of the
    # same snapshot. Patch the generator, then run it.
    refresh = ROOT / REFRESH
    before = (ROOT / "tests/fixtures/live-state/phases.json").read_text(encoding="utf-8")
    done = subprocess.run([sys.executable, str(refresh)], cwd=ROOT,
                          capture_output=True, text=True)
    if done.returncode != 0:
        print(f"migrate-schema3: {REFRESH} failed after the edits were written:\n"
              f"{done.stdout}{done.stderr}", file=sys.stderr)
        return 2
    after = (ROOT / "tests/fixtures/live-state/phases.json").read_text(encoding="utf-8")
    if after == before:
        print("migrate-schema3: refresh.py rewrote phases.json to what it already said. "
              "The snapshot has not picked up the estate.", file=sys.stderr)
        return 2
    print(f"  regenerated tests/fixtures/live-state/phases.json — {done.stdout.strip()}")

    print(f"migrate-schema3: applied to {len(planned)} files.")
    print("Now: make site-page && make site-data, then scripts/verify-schema3.sh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
