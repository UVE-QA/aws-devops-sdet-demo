def migrate_node_states_stub(doc: dict) -> dict:
    """tests/fixtures/node-states/topology.json — schema 2 stub -> three contours."""
    if doc.get("schema") == 3:
        raise AlreadyApplied()
    if doc.get("schema") != 2 or "phases" not in doc:
        raise Refusal("tests/fixtures/node-states/topology.json is neither schema 2 nor schema 3")

    environments: dict[str, list[dict]] = {}
    phases = []
    for phase in doc["phases"]:
        own, touches = [], []
        for node in phase["nodes"]:
            # The teardown is the only VERB node in this stub: it is what a
            # cycle DOES, it carries no members, and node-states matches a
            # delete to it by environment rather than by address.
            if node.get("service") == "destroy":
                own.append(node)
            else:
                environments.setdefault(node["env"], []).append(node)
                touches.append({"node": node["id"], "verb": "creates"})
        if own:
            for node in own:
                touches += [
                    {"node": member["id"], "verb": "destroys"}
                    for member in environments.get(node["env"], [])
                ]
        phases.append(
            {
                "id": phase["id"],
                "n": phase["n"],
                "label": phase["label"],
                "workflow": phase["workflow"],
                "nodes": own,
                "touches": touches,
            }
        )

    return {
        "_": doc["_"],
        "_env": doc["_env"],
        "_contours": (
            "Schema 3. The estate holds what EXISTS and carries every member; the cycle "
            "holds what a run DOES and references the rest through `touches`. Kept as two "
            "contours here rather than flattened back for the test's convenience, because "
            "the join under test is exactly the resolution between them: read off "
            "phases[].nodes, index_members() returns an empty dict and every address in "
            "these fixtures reads as unknown."
        ),
        "schema": 3,
        "not_shown": doc["not_shown"],
        "estate": {
            "permanent": [],
            "environments": [
                {"id": env, "level": f"infra/envs/{env}", "nodes": nodes}
                for env, nodes in environments.items()
            ],
        },
        "cycle": {"phases": phases},
    }


