#!/usr/bin/env python3
"""Point the four remaining consumers at site/data/topology.json's schema 3.

Phase 22 split the map's data into three contours - `estate` (what exists),
`cycle` (what a run does to it) and `assertions` (what is claimed about it).
The generator and its gate moved together, so `make site-data-check` went green
and stayed green. Four readers did not move, and NONE of them went red, because
every one of them is gated against a FROZEN schema-2 fixture:

    scripts/node-states.py            four indexers walking phases[].nodes.
                                      index_members() returned ZERO addresses
                                      against the real file - every resource of
                                      a live cycle would have been reported
                                      UNKNOWN, which is the one channel that is
                                      supposed to be rare
    assets/index.template.html        DATA.phases and p.nodes: the map would
                                      have thrown on load
    scripts/fold-results.py           the suite ids, read through
                                      topology["phases"] (the gate over it is
                                      scripts/check-results.py)
    tests/fixtures/live-state/        refresh.py, which regenerates the frozen
                                      phase snapshot from the real file

A green gate over a frozen fixture proves that the fixture and the code agree.
It says nothing about the file the code will actually be handed, and that is
the whole reason this script exists rather than a hand edit per site.

WHY A SCRIPT AND NOT A HEREDOC
------------------------------
docs/session-primer.md: prefer a checked-in patch script over a long
interactive heredoc, because it fails loudly and changes nothing on mismatch.

AND THE FAILURE THAT SHAPE HAS ALREADY HAD HERE. Phase 19g's patch script
computed every replacement FROM THE ORIGINAL TEXT and wrote them one after
another, so the second edit to a file silently discarded the first - and it
printed success twice (docs/phase-gates.md, Phase 19g). So: each file is read
ONCE into a string, every edit for that file is applied to THAT STRING in
sequence, and the string is written ONCE. No replacement is ever recomputed
from the text on disk.

THE REFUSAL CONTRACT
--------------------
    every anchor matches EXACTLY ONCE      -> everything is written
    an anchor matches 0 or 2+ times        -> NOTHING is written, exit 2
    every anchor is already gone and every
    replacement is already present         -> exit 3, "already applied"
    some applied and some not              -> NOTHING is written, exit 2

Exit 3 is a refusal too, and a loud one - it exists so that
scripts/verify-schema3.sh can be run twice without the second run reading as a
failure. A half-migrated tree is never a state this script can leave behind:
the writes happen after every edit in every file has been proved to match.

    scripts/migrate-schema3.py            # apply
    scripts/migrate-schema3.py --dry-run  # prove the anchors match, write nothing

AFTERWARDS, and NOT as a string edit: tests/fixtures/live-state/phases.json is
GENERATED by tests/fixtures/live-state/refresh.py. This script patches the
generator and then runs it. Hand-writing the snapshot beside its generator
would be a second definition of the same thing, which is the shape this
repository keeps deleting.
"""

