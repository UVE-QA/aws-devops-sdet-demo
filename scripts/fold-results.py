#!/usr/bin/env python3
"""Fold the test reporters' own output onto the map's suite nodes (ADR-0042 D5).

The inventory (site/data/suites.json) is what the repository CONTAINS. This is
what a run SAID about it, and the two are joined here rather than on the page,
for the reason the node-states fold gives: written twice, in JavaScript there and
in Python here, it would be one definition on two hosts, and this project has
already paid for that once.

Inputs are the reporters' native formats, not a summary written by a workflow
step:

    --junit <suite>=<file>   pytest --junitxml, one per pytest suite
    --playwright <file>      the JSON reporter, holding BOTH projects
    --db-log <file>          the db assertion's stdout, PASS/FAIL/SKIP per check

WHAT THIS REFUSES TO DO. It never invents a verdict. A suite the map draws for
this environment and this run did not report is `unobserved`; a test in the
inventory the report does not mention is `not_run` and makes its suite
`incomplete`; a test the report mentions and the inventory does not is recorded
in `unknown` and named in the output. An empty result is not a clean result -
the post-teardown check that printed `ecs :`, `rds :`, `alb :` and read as
success is the reason that sentence is in this file.

THE NODE IDS COME FROM THE MAP, NOT FROM A PATTERN. `suite.<name>.<environment>`
is how they happen to be spelled today; constructing one and publishing it would
mean a rename on the map turns into a result that lands on nothing, silently. So
each id is looked up in site/data/topology.json and an id that is not there is a
refusal.

    scripts/fold-results.py --environment stage --run-id 42 --workflow deploy-stage \\
        --junit api=/tmp/junit-api.xml --playwright /tmp/report.json \\
        --db-log /tmp/db-assert.txt --out /tmp/results.json
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "site/data/suites.json"
TOPOLOGY = ROOT / "site/data/topology.json"

HEADER = (
    "GENERATED by scripts/fold-results.py from the test reporters' own output - "
    "pytest --junitxml, the Playwright JSON reporter, and the db assertion's stdout. "
    "One object per RUN, published beside the timeline. A suite this run did not "
    "report is listed as unobserved rather than drawn in any colour, and a test the "
    "inventory names and the report does not mention is not_run, which makes its "
    "suite incomplete. Nothing here is a default."
)

# Playwright's per-test outcomes, mapped onto the three this file publishes.
# `interrupted` is deliberately not a failure: it is the shape a cancelled run
# leaves, and calling it failed would accuse a test of something the run never
# found out.
PW_STATUS = {
    "expected": "passed",
    "passed": "passed",
    "unexpected": "failed",
    "failed": "failed",
    "timedOut": "failed",
    "flaky": "passed",
    "skipped": "skipped",
    "interrupted": "incomplete",
}


class Refusal(Exception):
    """Something is missing or ambiguous enough that folding anything would lie."""


# ------------------------------------------------------------------ readers


def read_junit(path: pathlib.Path) -> list[dict]:
    if not path.is_file():
        raise Refusal(f"{path} does not exist")
    try:
        root = ET.parse(path).getroot()
    except ET.ParseError as e:
        raise Refusal(f"{path} is not parsable XML: {e}")

    cases = []
    for case in root.iter("testcase"):
        status = "passed"
        if case.find("failure") is not None or case.find("error") is not None:
            status = "failed"
        elif case.find("skipped") is not None:
            status = "skipped"
        # pytest writes classname as the dotted module path; the inventory
        # speaks in file paths, so the join happens on the test NAME within a
        # suite. Names are unique per suite in this repository, and a duplicate
        # is caught below rather than silently overwritten.
        cases.append(
            {
                "name": case.get("name", ""),
                "status": status,
                "duration_s": round(float(case.get("time") or 0.0), 3),
            }
        )
    if not cases:
        raise Refusal(f"{path} holds no testcase elements. A report with no tests is not a pass.")
    return cases


def read_playwright(path: pathlib.Path) -> dict[str, list[dict]]:
    """Return {project: [test, ...]}. One report holds every project that ran."""
    if not path.is_file():
        raise Refusal(f"{path} does not exist")
    try:
        report = json.loads(path.read_text())
    except json.JSONDecodeError as e:
        # A truncated report is what a killed run leaves behind, and it is the
        # case this whole family of folds exists for. It is a refusal, not an
        # empty suite: the caller decides what an absent report means.
        raise Refusal(f"{path} is not parsable JSON, which is what a killed run leaves: {e}")

    by_project: dict[str, list[dict]] = {}

    def walk(node, titles):
        for spec in node.get("specs", []):
            for test in spec.get("tests", []):
                project = test.get("projectName") or ""
                results = test.get("results") or []
                raw = (results[-1].get("status") if results else None) or test.get("status") or ""
                status = PW_STATUS.get(raw)
                if status is None:
                    raise Refusal(
                        f"unknown Playwright status {raw!r} for '{spec.get('title')}'. "
                        "Mapping it to anything would be a verdict this script invented."
                    )
                duration = sum(float(r.get("duration") or 0) for r in results) / 1000.0
                by_project.setdefault(project, []).append(
                    {
                        "name": " > ".join(titles + [spec["title"]]),
                        "status": status,
                        "duration_s": round(duration, 3),
                    }
                )
        for child in node.get("suites", []):
            walk(child, titles + [child.get("title", "")])

    for top in report.get("suites", []):
        walk(top, [])
    if not by_project:
        raise Refusal(f"{path} names no project. A report with no tests is not a pass.")
    return by_project


DB_LINE = re.compile(r"^(PASS|FAIL|SKIP):\s+(\S+)")


def read_db_log(path: pathlib.Path) -> list[dict]:
    """The db assertion reports itself in text, because in AWS it is an ECS task.

    Its stdout is the only channel: `ecs-run-task.sh` observes an exit code, and
    the task's log is where the checks say which of them failed. Parsing text is
    the price of that, and it is bounded - the format is one line per check,
    written by a file in this repository, gated by the same inventory.
    """
    if not path.is_file():
        raise Refusal(f"{path} does not exist")
    tests = []
    for line in path.read_text().splitlines():
        m = DB_LINE.match(line.strip())
        if not m:
            continue
        verdict, name = m.groups()
        tests.append(
            {
                "name": name,
                "status": {"PASS": "passed", "FAIL": "failed", "SKIP": "skipped"}[verdict],
                "duration_s": None,
            }
        )
    if not tests:
        raise Refusal(
            f"{path} holds no PASS/FAIL/SKIP line. The db assertion prints one per check; "
            "a log without any is a task that never reached them, not a suite that passed."
        )
    return tests


# --------------------------------------------------------------------- fold


def join(inventory_tests: list[dict], reported: list[dict], suite: str) -> tuple[list[dict], list[str]]:
    """Join a report onto the inventory. Neither side is allowed to disappear."""
    seen: dict[str, dict] = {}
    for t in reported:
        if t["name"] in seen:
            raise Refusal(
                f"suite '{suite}' reported '{t['name']}' twice. The join is by name; "
                "two results under one name cannot both be published."
            )
        seen[t["name"]] = t

    tests, unknown = [], []
    for inv in inventory_tests:
        got = seen.pop(inv["name"], None)
        entry = {"name": inv["name"], "file": inv["file"]}
        if got is None:
            entry["status"] = "not_run"
            entry["duration_s"] = None
        else:
            entry["status"] = got["status"]
            entry["duration_s"] = got["duration_s"]
        if "asserts" in inv:
            entry["asserts"] = inv["asserts"]
        tests.append(entry)

    # Anything the report has and the inventory does not. Loud, and kept.
    unknown = sorted(seen)
    return tests, unknown


def suite_status(tests: list[dict]) -> str:
    statuses = {t["status"] for t in tests}
    if "failed" in statuses:
        return "failed"
    if "incomplete" in statuses or "not_run" in statuses:
        return "incomplete"
    if statuses <= {"skipped"}:
        return "incomplete"
    return "passed"


def fold(args) -> dict:
    inventory = json.loads(pathlib.Path(args.inventory).read_text())["suites"]
    topology = json.loads(pathlib.Path(args.topology).read_text())
    node_ids = {
        n["id"] for phase in topology["phases"] for n in phase["nodes"] if n.get("kind") == "suite"
    }

    reported: dict[str, list[dict]] = {}

    for pair in args.junit or []:
        if "=" not in pair:
            raise Refusal(f"--junit expects <suite>=<file>, got {pair!r}")
        suite, path = pair.split("=", 1)
        if suite not in inventory:
            raise Refusal(f"--junit names suite '{suite}', which the inventory does not have")
        reported[suite] = read_junit(pathlib.Path(path))

    if args.playwright:
        by_project = read_playwright(pathlib.Path(args.playwright))
        for project, tests in by_project.items():
            # The inventory keys ARE the project names for the playwright
            # suites, and collect-suites.py records the project it asked for.
            if project not in inventory:
                raise Refusal(
                    f"the Playwright report names project '{project}', which is not a suite in "
                    "the inventory. A project the map does not know about would land nowhere."
                )
            reported[project] = tests

    if args.db_log:
        reported["db"] = read_db_log(pathlib.Path(args.db_log))

    if not reported:
        raise Refusal("no report was given. Folding nothing produces a page that says everything passed.")

    nodes, unobserved, unknown_all = {}, [], {}
    for suite in sorted(inventory):
        node_id = f"suite.{suite}.{args.environment}"
        if suite not in reported:
            # Not every suite runs in every environment - ADR-0025 keeps the
            # destructive ones away from prod - so a suite with no report is
            # only interesting if the map draws it here.
            if node_id in node_ids:
                unobserved.append(node_id)
            continue
        if node_id not in node_ids:
            raise Refusal(
                f"suite '{suite}' reported a result for environment '{args.environment}', and the "
                f"map has no node '{node_id}'. Either the run did something the map does not "
                "describe, or a node was renamed and this result would land on nothing."
            )

        tests, unknown = join(inventory[suite]["tests"], reported[suite], suite)
        if unknown:
            unknown_all[node_id] = unknown
        counts = {"passed": 0, "failed": 0, "skipped": 0, "not_run": 0, "incomplete": 0}
        for t in tests:
            counts[t["status"]] = counts.get(t["status"], 0) + 1
        durations = [t["duration_s"] for t in tests if t["duration_s"] is not None]
        nodes[node_id] = {
            "suite": suite,
            "status": suite_status(tests),
            "counts": counts,
            "duration_s": round(sum(durations), 3) if durations else None,
            "tests": tests,
        }

    return {
        "_": HEADER,
        "schema": 1,
        "environment": args.environment,
        "run": {"id": args.run_id, "workflow": args.workflow, "url": args.run_url},
        "nodes": nodes,
        "unobserved": sorted(unobserved),
        "unknown": unknown_all,
    }


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--environment", required=True)
    p.add_argument("--run-id", default=None)
    p.add_argument("--workflow", default=None)
    p.add_argument("--run-url", default=None)
    p.add_argument("--junit", action="append", metavar="SUITE=FILE")
    p.add_argument("--playwright", metavar="FILE")
    p.add_argument("--db-log", metavar="FILE")
    p.add_argument("--inventory", default=str(INVENTORY))
    p.add_argument("--topology", default=str(TOPOLOGY))
    p.add_argument("--out", required=True)
    args = p.parse_args()

    try:
        data = fold(args)
    except Refusal as e:
        print(f"results: REFUSED\n{e}")
        return 1

    pathlib.Path(args.out).write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    line = ", ".join(
        f"{n.split('.')[1]} {v['status']} ({v['counts']['passed']}/{len(v['tests'])})"
        for n, v in data["nodes"].items()
    )
    print(f"results: wrote {args.out} - {line or 'nothing'}")
    if data["unobserved"]:
        print("results: unobserved on this map - " + ", ".join(data["unobserved"]))
    for node, names in data["unknown"].items():
        print(f"results: {node} reported {len(names)} test(s) the inventory does not have: {', '.join(names)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
